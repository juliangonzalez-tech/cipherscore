import { beforeAll, describe, expect, it, vi } from "vitest";
import { lengthAdvice } from "@/lib/guidance";
import {
  ANALYSIS_MAX_LENGTH,
  SCORE_LABELS,
  StrengthEstimator,
  loadStrengthEstimator
} from "@/lib/strength";
import { DEFAULT_PASSPHRASE_OPTIONS, generatePassphrase } from "@/lib/password-generator";

let estimate: StrengthEstimator;

beforeAll(async () => {
  estimate = await loadStrengthEstimator();
});

describe("strength estimation (zxcvbn-ts)", () => {
  it.each(["password", "123456", "qwerty", "letmein", "iloveyou", "aaaaaaaa", "abcdefgh"])(
    "rates the common or patterned password %j as very guessable or guessable",
    (password) => {
      expect(estimate(password).score).toBeLessThanOrEqual(1);
    }
  );

  it("explains why a top password is weak", () => {
    const result = estimate("password");
    expect(result.score).toBe(0);
    expect(result.warning).toBeTruthy();
  });

  it("recognises common substitutions, so 'P@ssw0rd' is not treated as strong", () => {
    expect(estimate("P@ssw0rd").score).toBeLessThanOrEqual(1);
  });

  it("rates a long random string and a long random passphrase as very hard to guess", () => {
    expect(estimate("tZ7#kQ9!vL2@mX5&Rw8").score).toBe(4);
    expect(estimate("sulphate-unwed-crimson-perkiness-ladle-spotter").score).toBe(4);
  });

  it("rates a passphrase generated by this app at the top of the scale", () => {
    const phrase = generatePassphrase({ ...DEFAULT_PASSPHRASE_OPTIONS, words: 6, separator: " " });
    expect(estimate(phrase).score).toBe(4);
  });

  it("orders guess counts sensibly: longer random input needs more guesses", () => {
    expect(estimate("tZ7#kQ9!vL2@mX5&Rw8").guessesLog10).toBeGreaterThan(estimate("tZ7#kQ9!").guessesLog10);
    expect(estimate("tZ7#kQ9!").guessesLog10).toBeGreaterThan(estimate("password").guessesLog10);
  });

  it("labels every score without promising security", () => {
    expect(Object.keys(SCORE_LABELS)).toHaveLength(5);
    for (const label of Object.values(SCORE_LABELS)) {
      expect(label).not.toMatch(/secure|safe|excellent|unbreakable|uncrackable/i);
    }
    expect(estimate("password").label).toBe(SCORE_LABELS[0]);
  });

  it("handles the empty string without throwing", () => {
    expect(estimate("").score).toBe(0);
  });

  it("handles unicode, emoji and spaces", () => {
    expect(() => estimate("pässwörd with spaces 🔐🔐")).not.toThrow();
  });
});

describe("strength estimation: input limits", () => {
  it("reports when only the first part of a very long input was analyzed", () => {
    const long = estimate("aB3$".repeat(100));
    expect(long.truncated).toBe(true);
    expect(long.analyzedCharacters).toBe(ANALYSIS_MAX_LENGTH);

    const short = estimate("aB3$".repeat(10));
    expect(short.truncated).toBe(false);
    expect(short.analyzedCharacters).toBe(40);
  });

  it("stays responsive on a repetitive worst-case input at the analysis limit", () => {
    const hostile = "a1!B2@c3#".repeat(40);
    const started = performance.now();
    estimate(hostile);
    // Roughly 0.3 s locally. The bound is loose for slow CI machines; the old 256-character
    // limit with fuzzy matching took 1.5 s or more.
    expect(performance.now() - started).toBeLessThan(1500);
  });

  it("stays responsive on a typical short password", () => {
    const started = performance.now();
    estimate("tZ7#kQ9!vL2@mX5&Rw8");
    expect(performance.now() - started).toBeLessThan(500);
  });
});

describe("strength estimation: privacy", () => {
  const secret = "Tr0ub4dor&3-horse-staple-xyzzy";

  it("returns only derived values: never the password or its matched substrings", () => {
    const result = estimate(secret);

    expect(Object.keys(result).sort()).toEqual(
      ["analyzedCharacters", "guessesLog10", "label", "score", "suggestions", "truncated", "warning"].sort()
    );
    const serialized = JSON.stringify(result).toLowerCase();
    for (const fragment of [secret, "tr0ub4dor", "horse", "staple", "xyzzy"]) {
      expect(serialized).not.toContain(fragment.toLowerCase());
    }
  });

  it("makes no network request and writes no logs while estimating", async () => {
    const fetchSpy = vi.fn();
    vi.stubGlobal("fetch", fetchSpy);
    const consoleSpies = (["log", "info", "warn", "error", "debug"] as const).map((method) =>
      vi.spyOn(console, method)
    );

    estimate(secret);
    await loadStrengthEstimator();

    expect(fetchSpy).not.toHaveBeenCalled();
    for (const spy of consoleSpies) expect(spy).not.toHaveBeenCalled();
  });

  it("reuses a single loaded estimator", async () => {
    expect(await loadStrengthEstimator()).toBe(await loadStrengthEstimator());
  });
});

describe("lengthAdvice (NIST SP 800-63B-4)", () => {
  it("is silent for an empty field and for passwords of 15 characters or more", () => {
    expect(lengthAdvice(0)).toBeNull();
    expect(lengthAdvice(15)).toBeNull();
    expect(lengthAdvice(64)).toBeNull();
  });

  it("flags anything shorter than 15 and states the actual length", () => {
    const advice = lengthAdvice(14);
    expect(advice).toMatch(/15 characters/);
    expect(advice).toMatch(/\b14\b/);
    expect(lengthAdvice(1)).not.toBeNull();
  });

  it("does not crash on nonsense input", () => {
    expect(lengthAdvice(Number.NaN)).toBeNull();
    expect(lengthAdvice(-3)).toBeNull();
  });
});
